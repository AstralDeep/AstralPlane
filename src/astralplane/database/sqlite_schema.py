def _declared_type_guards(statement: str) -> str:
    if not statement.startswith("CREATE TABLE "):
        return statement
    table = statement.split()[2].strip('"')
    scalar_types = SQLITE_SCALAR_TYPES.get(table, {})
    lines = []
    for line in statement.split("\n"):
        match = re.match(
            r'^\s+("[^"]+"|\w+)\s+(TIMESTAMPTZ|BOOLEAN|JSONB|JSONARRAY|INTEGER|REAL|BLOB|TEXT)\b',
            line,
        )
        if match is not None:
            column, kind = match.groups()
            expression = {
                "TIMESTAMPTZ": f"astral_timestamp_is_valid({column})",
                "BOOLEAN": f"typeof({column})='integer' AND {column} IN (0,1)",
                "INTEGER": f"typeof({column})='integer'",
                "REAL": f"typeof({column}) IN ('integer','real')",
                "BLOB": f"typeof({column})='blob'",
                "JSONB": f"astral_jsonb_is_valid({column})",
                "JSONARRAY": f"astral_jsonb_is_valid({column}) AND json_type({column})='array'",
                "TEXT": f"typeof({column})='text' AND instr({column},char(0))=0",
            }[kind]
            scalar_type = scalar_types.get(column.strip('"'))
            if scalar_type == "uuid":
                expression += f" AND astral_uuid_is_canonical({column})"
            elif scalar_type in {"int2", "int4", "int8"}:
                bits = {"int2": 16, "int4": 32, "int8": 64}[scalar_type]
                expression += (
                    f" AND {column} BETWEEN {-(1 << (bits - 1))} AND {(1 << (bits - 1)) - 1}"
                )
            comma = "," if line.endswith(",") else ""
            line = line.removesuffix(",") + f" CHECK({column} IS NULL OR ({expression}))" + comma
        lines.append(line)
    return "\n".join(lines)


